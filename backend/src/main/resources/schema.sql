-- PostgreSQL schema for users, channels, and channel subscriptions.
CREATE TABLE IF NOT EXISTS accounts (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    firstname VARCHAR(100) NOT NULL,
    lastname VARCHAR(100) NOT NULL,
    email VARCHAR(320) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS channel (
    channel_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES accounts (user_id) ON DELETE CASCADE,
    channel_name VARCHAR(255) NOT NULL
);


-- DISCUSS WITH ZAK
CREATE TABLE IF NOT EXISTS subscriptions (
    user_id BIGINT NOT NULL REFERENCES accounts (user_id) ON DELETE CASCADE,
    channel_id BIGINT NOT NULL REFERENCES channel (channel_id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, channel_id)
);

CREATE TABLE IF NOT EXISTS video (
    video_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id BIGINT NOT NULL REFERENCES channel (channel_id) ON DELETE CASCADE,
    video BYTEA NOT NULL,
    video_content_type VARCHAR(100) NOT NULL DEFAULT 'video/mp4',
    thumbnail BYTEA,
    thumbnail_content_type VARCHAR(100),
    title VARCHAR(255) NOT NULL,
    duration TIME NOT NULL
);

CREATE TABLE IF NOT EXISTS video_comment (
    comment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    video_id BIGINT NOT NULL REFERENCES video (video_id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES accounts (user_id) ON DELETE CASCADE,
    content TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

