-- PostgreSQL schema for Stripe payments, channel memberships, Premium and creator payouts.
-- Runs after schema.sql on every start, so every statement must be idempotent.
-- Money is stored in minor units (pence) with a 3-letter lowercase ISO currency.
-- Local ids are BIGINT identities; Stripe ids are kept in separate stripe_*_id columns.

-- Members-only playback
ALTER TABLE video ADD COLUMN IF NOT EXISTS visibility VARCHAR(20) NOT NULL DEFAULT 'PUBLIC'
    CHECK (visibility IN ('PUBLIC', 'UNLISTED', 'PRIVATE', 'MEMBERS_ONLY'));
ALTER TABLE video ADD COLUMN IF NOT EXISTS required_tier_level INT
    CHECK (required_tier_level BETWEEN 1 AND 10);

CREATE TABLE IF NOT EXISTS payment_customers (
    payment_customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES accounts (user_id) ON DELETE CASCADE,
    stripe_customer_id VARCHAR(255) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS channel_membership_tiers (
    tier_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id BIGINT NOT NULL REFERENCES channel (channel_id) ON DELETE CASCADE,
    name VARCHAR(80) NOT NULL,
    description VARCHAR(500),
    level INT NOT NULL CHECK (level BETWEEN 1 AND 10),
    price_minor BIGINT NOT NULL CHECK (price_minor > 0),
    currency CHAR(3) NOT NULL DEFAULT 'gbp',
    stripe_product_id VARCHAR(255) UNIQUE,
    stripe_price_id VARCHAR(255) UNIQUE,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_tiers_active_channel_level
    ON channel_membership_tiers (channel_id, level) WHERE active;

CREATE TABLE IF NOT EXISTS membership_perks (
    perk_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tier_id BIGINT NOT NULL REFERENCES channel_membership_tiers (tier_id) ON DELETE CASCADE,
    perk_type VARCHAR(40) NOT NULL CHECK (perk_type IN ('MEMBERS_ONLY_VIDEOS', 'MEMBERS_ONLY_SHORTS',
        'MEMBERS_ONLY_LIVESTREAMS', 'EARLY_ACCESS', 'COMMUNITY_POSTS', 'LOYALTY_BADGE', 'CUSTOM_EMOJI',
        'MEMBERS_ONLY_CHAT', 'CUSTOM')),
    description VARCHAR(255) NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_perks_tier ON membership_perks (tier_id);

CREATE TABLE IF NOT EXISTS checkout_sessions (
    checkout_session_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stripe_checkout_session_id VARCHAR(255) NOT NULL UNIQUE,
    user_id BIGINT NOT NULL REFERENCES accounts (user_id) ON DELETE CASCADE,
    purpose VARCHAR(30) NOT NULL CHECK (purpose IN ('CHANNEL_MEMBERSHIP', 'PREMIUM', 'TIP')),
    channel_id BIGINT REFERENCES channel (channel_id) ON DELETE CASCADE,
    tier_id BIGINT REFERENCES channel_membership_tiers (tier_id) ON DELETE CASCADE,
    status VARCHAR(20) NOT NULL CHECK (status IN ('OPEN', 'COMPLETE', 'EXPIRED')),
    checkout_url TEXT,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_checkout_open
    ON checkout_sessions (user_id, purpose, channel_id) WHERE status = 'OPEN';

CREATE TABLE IF NOT EXISTS channel_memberships (
    membership_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES accounts (user_id) ON DELETE CASCADE,
    channel_id BIGINT NOT NULL REFERENCES channel (channel_id) ON DELETE CASCADE,
    tier_id BIGINT NOT NULL REFERENCES channel_membership_tiers (tier_id),
    stripe_subscription_id VARCHAR(255) NOT NULL UNIQUE,
    stripe_customer_id VARCHAR(255) NOT NULL,
    -- Mirrors Stripe's subscription status
    status VARCHAR(30) NOT NULL CHECK (status IN ('incomplete', 'incomplete_expired', 'trialing', 'active',
        'past_due', 'canceled', 'unpaid', 'paused')),
    cancel_at_period_end BOOLEAN NOT NULL DEFAULT FALSE,
    current_period_end TIMESTAMPTZ,
    -- Last entitlement state published to Kafka; used to detect activated/expired transitions
    entitled BOOLEAN NOT NULL DEFAULT FALSE,
    last_synced_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- At most one live membership per viewer per channel. Tier changes update the row; they never add one.
CREATE UNIQUE INDEX IF NOT EXISTS ux_memberships_live_user_channel
    ON channel_memberships (user_id, channel_id)
    WHERE status IN ('incomplete', 'trialing', 'active', 'past_due', 'unpaid', 'paused');
CREATE INDEX IF NOT EXISTS ix_memberships_user ON channel_memberships (user_id);

CREATE TABLE IF NOT EXISTS premium_subscriptions (
    premium_subscription_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES accounts (user_id) ON DELETE CASCADE,
    stripe_subscription_id VARCHAR(255) NOT NULL UNIQUE,
    stripe_price_id VARCHAR(255) NOT NULL,
    status VARCHAR(30) NOT NULL CHECK (status IN ('incomplete', 'incomplete_expired', 'trialing', 'active',
        'past_due', 'canceled', 'unpaid', 'paused')),
    cancel_at_period_end BOOLEAN NOT NULL DEFAULT FALSE,
    current_period_end TIMESTAMPTZ,
    entitled BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_premium_live_user
    ON premium_subscriptions (user_id)
    WHERE status IN ('incomplete', 'trialing', 'active', 'past_due', 'unpaid', 'paused');

CREATE TABLE IF NOT EXISTS payments (
    payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- SET NULL keeps the financial record when an account is erased
    user_id BIGINT REFERENCES accounts (user_id) ON DELETE SET NULL,
    purpose VARCHAR(30) NOT NULL CHECK (purpose IN ('CHANNEL_MEMBERSHIP', 'PREMIUM', 'TIP')),
    channel_id BIGINT REFERENCES channel (channel_id) ON DELETE SET NULL,
    membership_id BIGINT REFERENCES channel_memberships (membership_id) ON DELETE SET NULL,
    stripe_checkout_session_id VARCHAR(255) UNIQUE,
    stripe_invoice_id VARCHAR(255) UNIQUE,
    stripe_payment_intent_id VARCHAR(255) UNIQUE,
    amount_minor BIGINT NOT NULL CHECK (amount_minor >= 0),
    currency CHAR(3) NOT NULL,
    platform_fee_minor BIGINT NOT NULL DEFAULT 0,
    creator_earnings_minor BIGINT NOT NULL DEFAULT 0,
    status VARCHAR(30) NOT NULL CHECK (status IN ('PENDING', 'SUCCEEDED', 'FAILED', 'REFUNDED',
        'PARTIALLY_REFUNDED', 'DISPUTED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_payments_user ON payments (user_id);
CREATE INDEX IF NOT EXISTS ix_payments_channel ON payments (channel_id);

CREATE TABLE IF NOT EXISTS refund_records (
    refund_record_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id BIGINT REFERENCES payments (payment_id) ON DELETE SET NULL,
    kind VARCHAR(20) NOT NULL CHECK (kind IN ('REFUND', 'DISPUTE')),
    stripe_charge_id VARCHAR(255) NOT NULL,
    stripe_dispute_id VARCHAR(255) UNIQUE,
    amount_minor BIGINT NOT NULL,
    currency CHAR(3) NOT NULL,
    status VARCHAR(40) NOT NULL,
    reason VARCHAR(100),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- One cumulative refund row per charge; disputes are keyed by dispute id
CREATE UNIQUE INDEX IF NOT EXISTS ux_refund_records_charge_refund
    ON refund_records (stripe_charge_id) WHERE kind = 'REFUND';

CREATE TABLE IF NOT EXISTS creator_stripe_accounts (
    creator_stripe_account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES accounts (user_id) ON DELETE CASCADE,
    stripe_account_id VARCHAR(255) NOT NULL UNIQUE,
    transfers_capability_status VARCHAR(30) NOT NULL DEFAULT 'unrequested',
    requirements_due BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS creator_earnings (
    creator_earning_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    creator_user_id BIGINT REFERENCES accounts (user_id) ON DELETE SET NULL,
    channel_id BIGINT REFERENCES channel (channel_id) ON DELETE SET NULL,
    payment_id BIGINT REFERENCES payments (payment_id) ON DELETE SET NULL,
    entry_type VARCHAR(30) NOT NULL CHECK (entry_type IN ('EARNING', 'REFUND_REVERSAL', 'DISPUTE_REVERSAL',
        'TRANSFER', 'TRANSFER_REVERSAL', 'ADJUSTMENT')),
    -- Signed: earnings positive, reversals negative
    amount_minor BIGINT NOT NULL,
    currency CHAR(3) NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('PENDING', 'AVAILABLE', 'TRANSFERRED', 'REVERSED')),
    stripe_transfer_id VARCHAR(255),
    available_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (payment_id, entry_type)
);
CREATE INDEX IF NOT EXISTS ix_creator_earnings_creator ON creator_earnings (creator_user_id, status);

CREATE TABLE IF NOT EXISTS webhook_inbox (
    webhook_inbox_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stripe_event_id VARCHAR(255) NOT NULL UNIQUE,
    event_type VARCHAR(100) NOT NULL,
    livemode BOOLEAN NOT NULL,
    payload TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'RECEIVED' CHECK (status IN ('RECEIVED', 'PROCESSED', 'IGNORED', 'FAILED')),
    attempts INT NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_error VARCHAR(1000),
    received_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processed_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS ix_webhook_inbox_pending
    ON webhook_inbox (next_attempt_at) WHERE status = 'RECEIVED';

CREATE TABLE IF NOT EXISTS outbox_events (
    outbox_event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id UUID NOT NULL UNIQUE,
    topic VARCHAR(100) NOT NULL,
    event_key VARCHAR(100) NOT NULL,
    payload TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'PUBLISHED', 'FAILED')),
    attempts INT NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_error VARCHAR(1000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    published_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS ix_outbox_pending
    ON outbox_events (next_attempt_at) WHERE status = 'PENDING';
