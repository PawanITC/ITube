CREATE TABLE IF NOT EXISTS liked_video (
    liked_video_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES accounts (user_id) ON DELETE CASCADE,
    video_id BIGINT NOT NULL REFERENCES video (video_id) ON DELETE CASCADE,
    liked_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_liked_video_user_video UNIQUE (user_id, video_id)
);

CREATE INDEX IF NOT EXISTS idx_liked_video_user_time
    ON liked_video (user_id, liked_at DESC, liked_video_id DESC);
