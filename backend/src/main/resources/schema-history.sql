-- History is independent of the account/video relationships until that integration is ready.
CREATE TABLE IF NOT EXISTS watch_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id VARCHAR(255) NOT NULL,
    video_id BIGINT NOT NULL,
    watched_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_history_user_watched_id
    ON watch_history (user_id, watched_at, id);
