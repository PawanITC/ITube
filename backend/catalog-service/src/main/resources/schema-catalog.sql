-- Catalog domain (schema "catalog"): channels, channel subscriptions, video metadata and renditions.
-- Runs on every start of catalog-service, on EVERY catalog database (shard), so every statement must be idempotent.
--
-- Sharding: channel_id and video_id carry their logical shard in the top bits (ITubeBackend.sharding.ShardIds),
-- and a creator's channels, videos, renditions, subscriptions-to-their-channels and uploads are all on one shard,
-- so the foreign keys below never cross databases.
-- Video files, renditions and thumbnails live in object storage (S3; SeaweedFS locally); these tables keep their keys.
-- user_id columns hold identity.accounts ids with no foreign key (that domain may move to another database).
CREATE SCHEMA IF NOT EXISTS catalog;

CREATE TABLE IF NOT EXISTS catalog.channel (
    channel_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    channel_name VARCHAR(255) NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_channel_user ON catalog.channel (user_id);
CREATE INDEX IF NOT EXISTS ix_channel_name ON catalog.channel (channel_name);

CREATE TABLE IF NOT EXISTS catalog.subscriptions (
    user_id BIGINT NOT NULL,
    channel_id BIGINT NOT NULL REFERENCES catalog.channel (channel_id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, channel_id)
);
CREATE INDEX IF NOT EXISTS ix_subscriptions_channel ON catalog.subscriptions (channel_id);

CREATE TABLE IF NOT EXISTS catalog.video (
    video_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id BIGINT NOT NULL REFERENCES catalog.channel (channel_id) ON DELETE CASCADE,
    video_key VARCHAR(512),
    video_size_bytes BIGINT,
    video_content_type VARCHAR(100) NOT NULL DEFAULT 'video/mp4',
    thumbnail_key VARCHAR(512),
    thumbnail_content_type VARCHAR(100),
    title VARCHAR(255) NOT NULL,
    -- Optional, entered at upload (videos and ads alike)
    description VARCHAR(5000),
    duration TIME NOT NULL,
    processing_status VARCHAR(20) NOT NULL DEFAULT 'PROCESSING',
    visibility VARCHAR(20) NOT NULL DEFAULT 'PUBLIC'
        CHECK (visibility IN ('PUBLIC', 'UNLISTED', 'PRIVATE', 'MEMBERS_ONLY')),
    required_tier_level INT CHECK (required_tier_level BETWEEN 1 AND 10),
    -- An upload is either a normal VIDEO or an AD (at most one minute, checked by VideoService).
    -- Normal videos choose whether ads play in them; ad_count is spread evenly, at most one per 10 minutes.
    video_type VARCHAR(10) NOT NULL DEFAULT 'VIDEO' CHECK (video_type IN ('VIDEO', 'AD')),
    ads_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    ad_count INT NOT NULL DEFAULT 1,
    -- Unique viewers (see catalog.video_view)
    view_count BIGINT NOT NULL DEFAULT 0,
    -- Transcoding sweeper (TranscodeSweeper): a video stuck in PROCESSING is re-queued a few times before FAILED
    transcode_attempts INT NOT NULL DEFAULT 0,
    transcode_requested_at TIMESTAMP WITH TIME ZONE,
    -- HLS backfill (HlsBackfillJob): its own attempt count, so a failed conversion leaves the video's MP4 files alone
    hls_backfill_attempts INT NOT NULL DEFAULT 0,
    hls_backfill_requested_at TIMESTAMP WITH TIME ZONE,
    -- Feeds are merged across shards by time (ties broken by id)
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_video_channel ON catalog.video (channel_id);
CREATE INDEX IF NOT EXISTS ix_video_created ON catalog.video (created_at DESC, video_id DESC);
CREATE INDEX IF NOT EXISTS ix_video_processing ON catalog.video (processing_status, transcode_requested_at);

CREATE TABLE IF NOT EXISTS catalog.video_rendition (
    video_id BIGINT NOT NULL REFERENCES catalog.video (video_id) ON DELETE CASCADE,
    quality VARCHAR(20) NOT NULL,
    content_type VARCHAR(100) NOT NULL DEFAULT 'video/mp4',
    storage_key VARCHAR(512),
    size_bytes BIGINT,
    PRIMARY KEY (video_id, quality)
);

-- Who has viewed each video or ad, so view_count counts each viewer once. viewer_key is 'user:<account id>' for
-- signed-in viewers, or 'anon:<random id kept in the browser>'.
CREATE TABLE IF NOT EXISTS catalog.video_view (
    video_id BIGINT NOT NULL REFERENCES catalog.video (video_id) ON DELETE CASCADE,
    viewer_key VARCHAR(64) NOT NULL,
    viewed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (video_id, viewer_key)
);

-- Resumable uploads in progress. The browser sends the file as parts straight to object storage (an S3
-- multipart upload); this row remembers the upload so it can be resumed later. Deleted when the upload
-- completes (the video row takes over) or is discarded; UploadExpiryJob aborts expired ones.
-- No foreign key to channel: the expiry job must still find (and abort) uploads of deleted channels.
CREATE TABLE IF NOT EXISTS catalog.upload_session (
    upload_session_id UUID PRIMARY KEY,
    user_id BIGINT NOT NULL,
    channel_id BIGINT NOT NULL,
    storage_key VARCHAR(512) NOT NULL,
    storage_upload_id VARCHAR(1024) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'UPLOADING' CHECK (status IN ('UPLOADING', 'ASSEMBLED')),
    file_name VARCHAR(255) NOT NULL,
    file_size BIGINT NOT NULL,
    file_last_modified BIGINT NOT NULL,
    content_type VARCHAR(100) NOT NULL,
    part_size BIGINT NOT NULL,
    title VARCHAR(255) NOT NULL,
    description VARCHAR(5000),
    duration TIME NOT NULL,
    visibility VARCHAR(20) NOT NULL
        CHECK (visibility IN ('PUBLIC', 'UNLISTED', 'PRIVATE', 'MEMBERS_ONLY')),
    required_tier_level INT CHECK (required_tier_level BETWEEN 1 AND 10),
    video_type VARCHAR(10) NOT NULL DEFAULT 'VIDEO' CHECK (video_type IN ('VIDEO', 'AD')),
    ads_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    ad_count INT NOT NULL DEFAULT 1,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_upload_session_user ON catalog.upload_session (user_id);
CREATE INDEX IF NOT EXISTS ix_upload_session_expires ON catalog.upload_session (expires_at);

-- Shard directory: which logical shard each creator lives on. Only used on physical shard 0 (OwnerDirectory);
-- created everywhere so every catalog database has the same schema.
CREATE TABLE IF NOT EXISTS catalog.owner_shard (
    user_id BIGINT PRIMARY KEY,
    logical_shard INT NOT NULL
);

-- Id sequences for H2 (tests). PostgreSQL uses each id column's own identity sequence instead (IdAllocator).
CREATE SEQUENCE IF NOT EXISTS catalog.channel_ids;
CREATE SEQUENCE IF NOT EXISTS catalog.video_ids;
